if (typeof document !== 'undefined') {
  const selected = document.body.dataset.pageLanguage || 'en';
  document.querySelectorAll('[data-language]').forEach(button => {
    const active = button.dataset.language === selected;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
    button.addEventListener('click', () => {
      window.location.href = languageUrls[button.dataset.language] + window.location.hash;
    });
  });
  document.querySelectorAll('[data-shot]').forEach((button, index) => {
    button.dataset.title = galleryTitles[selected][index];
  });
  const activeShot = document.querySelector('[data-shot].active');
  if (activeShot) document.querySelector('#shot-title').textContent = activeShot.dataset.title;
}
