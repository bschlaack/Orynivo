const languageIndex = { en: 0, fr: 1, es: 2, ru: 3, zh: 4 };
const originalTextNodes = [];

function collectTextNodes() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      return node.nodeValue.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  let node;
  while ((node = walker.nextNode())) originalTextNodes.push({node, key: node.nodeValue.trim()});
}

function translatedValue(key, language) {
  if (language === 'de' || !translations[key]) return key;
  return translations[key][languageIndex[language]] || key;
}

function setTextNodeLanguage(entry, language) {
  const leading = entry.node.nodeValue.match(/^\s*/)[0];
  const trailing = entry.node.nodeValue.match(/\s*$/)[0];
  entry.node.nodeValue = `${leading}${translatedValue(entry.key, language)}${trailing}`;
}

